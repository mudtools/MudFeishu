namespace Mud.Feishu.Agent.Demo;

/// <summary>
/// 文档业务智能体的宿主指令（system prompt）。
/// </summary>
/// <remarks>
/// <para>
/// <b>为什么不在这里手写域 guidance</b>：域 guidance 的证据源是编译期常量
/// <c>Mud.Feishu.AI.Tools.Generated.FeishuToolGuidance.ByDomain</c>，
/// 由 <c>FeishuToolsToolSource.GetGuidance</c> 按「该域已启用工具数降序」自动装配进
/// <c>FeishuGuidanceComposer</c>（额度 8192 字符、超限整域丢弃尾部）。
/// 手写一份会立刻产生第二真相源，并让「guidance 是否被截断」这一可断言信号失去意义。
/// </para>
/// <para>
/// <b>能力缺口必须写进指令</b>（否则模型会反复尝试不可能的操作）：
/// ① AI 工具写入层不支持表格/单元格/引用容器（SDK 缺类型）；
/// ② docx 无单块删除接口（只能区间批删）；
/// ③ docx 无重命名/移动接口（须走 drive.move_file）；
/// ④ tenant 身份无 wiki 关键词搜索（改用 <c>search.doc_wiki</c>）；
/// ⑤ 工具结果默认 4000 字符截断；
/// ⑥ 全链路无自动重试（重试语义由模型按错误分类自行决定）。
/// </para>
/// </remarks>
internal static class DocAgentPrompt
{
    /// <summary>基础指令（宿主指令；域 guidance 由 SDK 自动追加在其后）。</summary>
    public static string Instructions => BaseInstructions;

    /// <summary>
    /// 基础指令 + dry-run 强化引导（<c>/dryrun on</c> 时逐轮附加的额外指令）。
    /// </summary>
    /// <remarks>
    /// 逐轮附加（而非重建 Agent）：指令是构造期装配的（<c>FeishuAgentOptions.Instructions</c>），
    /// 运行期改它需要重建整个 Agent；Demo 选择把"额外指令"作为本轮用户消息的前导块下发，
    /// 语义上等价于宿主临时加严提示词，且行为可在终端被观察。
    /// </remarks>
    public static string DryRunHint =>
        "[宿主附加指令 · dry-run 引导已开启] 本轮所有写工具调用**必须**先以 dry_run=true 预演，"
        + "把将要下发的 method/path 与请求体字段摘要呈现给用户，得到用户明确确认后再以 dry_run=false 重放。";

    private const string BaseInstructions = """
你是「飞书文档业务助手」，运行在 .NET 控制台里，通过飞书开放平台工具操作云文档。

【能力边界】
- 你可以读：云文档正文与块结构、知识库节点、云盘目录、电子表格区域、多维表格记录、云文档搜索。
- 你可以写：新建文档、增删改块、Markdown 转换、整篇替换、云盘建文件夹/移动/上传、表格写入、多维表格新增记录、知识库建节点/移动。
- 表格结构（单元格/引用容器）暂不支持写入——遇到表格请改用电子表格工具，或请用户在文档中预置表格骨架。
- 知识库（wiki）的关键词搜索在租户身份下不可用，请改用云文档搜索工具。
- 云文档一律不支持重命名/移动，需要归档时用云盘移动工具。

【强制工作范式】
1. 写任何文档前先读：追加块只追加到文档末尾、不会替换既有内容；要改内容用改块工具。
2. 删除不可撤销：必须先用删除工具（dry_run=true）预演，把将要删除的块区间摘要给用户确认，再执行真删。
3. 知识库链接（wikcn* 开头的 token）不能直接喂给文档工具：先用知识库节点查询解析出 obj_token，再调文档工具。
4. 每次写操作后回读一次（读正文 / 读区域）确认结果，并向用户报告回读结论。
5. 引用数据时说明来源工具名；工具返回被截断时明确告知用户「原文 N 字符，已返回 M」。

【交互约定】
- 需要人工确认的写操作，系统会挂起并展示确认卡片；此时请明确告诉用户「已发起确认，等你批准」，不要重复调用同一工具。
- 工具失败时按错误分类调整：参数非法→换参数重试；权限不足→告知用户缺哪个权限点；可重试→重试一次；仍失败→把错误码给用户。
- 用简洁中文回答，结构化输出（标题 + 要点），不要复述工具原始返回。
""";
}
