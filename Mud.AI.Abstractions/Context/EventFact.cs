namespace Mud.AI.Abstractions.Context;

/// <summary>
/// 事件上下文事实（<b>有序键值对</b>）：事件派发侧（生产者）→ 上下文装配器（消费者）之间的最小载体。
/// </summary>
/// <param name="Key">事实键（约定见各装配器；未登记的键按原样展示，不臆造语义）。</param>
/// <param name="Value">事实值（可空；空值由装配器跳过——不输出"审批实例: "这样的半截行）。</param>
/// <remarks>
/// <para>
/// <b>为什么是"有序列表"而不是字典</b>：装配结果会进 prompt，<b>顺序必须是确定的</b>；
/// 字典的枚举顺序在契约上未定义。列表同时天然表达"同一字段的变更前后配对"
/// （<c>diff.0</c> / <c>diff.1</c>…）。
/// </para>
/// <para>
/// <b>值可能含用户内容</b>（表格字段值、审批表单），故消费它的装配器<b>必须</b>带 untrusted 标注
/// 并逐行扣预算。
/// </para>
/// <para>
/// 中立化说明：本类型原名 <c>FeishuEventFact</c>。事件族判别键（<c>approval_task</c> /
/// <c>bitable_record_changed</c>）是<b>产品事实</b>，留在产品侧（<c>FeishuEventKeys</c>），
/// 不随本类型上移。
/// </para>
/// </remarks>
public readonly record struct EventFact(string Key, string? Value);
