namespace Mud.AI.Abstractions.Tools.Errors;

/// <summary>
/// 传输层故障端口（产品中立契约）：把一个异常所携带的 <b>HTTP 状态码</b>暴露给
/// 产品中立的错误分类器（<c>Mud.AI.Agent.Tools.Errors.ToolErrorClassifier</c>）。
/// </summary>
/// <remarks>
/// <para>
/// <b>为什么需要这一层（独立产品线纪律，不是冗余抽象）</b>：错误分类是运行期通用关注点，
/// 它的实现必须留在产品中立的 <c>Mud.AI.Agent</c>；而"HTTP 状态码"这一事实的唯一产出者
/// 是<b>产品侧</b>的传输组件（各产品的 HTTP 客户端异常）。若让中立层直接判定某个具体
/// HTTP 组件的异常类型，等于让独立产品线反向依赖组件包——P3 上游化（迁独立 Mud.AI 仓与包）
/// 时该依赖会被一并带走，且版本节奏被组件版本线牵制。
/// </para>
/// <para>
/// 故此处只保留<b>唯一的跨产品事实</b>（状态码）：具体异常类型的识别与适配由产品适配层完成
/// （消费方测试对"适配层确实接线"有端到端证据）。这与 <c>ISessionStore</c> 端口同属一个定式
/// ——接口形状可以相似，但生命周期与版本纪律不同，所以是<u>有意的接缝</u>而不是可以合并的重复类型。
/// </para>
/// <para>
/// <b>刻意只暴露状态码</b>：响应头（如 <c>Retry-After</c>）不进入本契约。扩大契约面会让
/// 每个产品都要提供自己可能没有的传输事实，端口随即退化成"具体组件的镜像"。
/// </para>
/// </remarks>
public interface ITransportFault
{
    /// <summary>HTTP 状态码；该故障不携带传输层语义时为 <see langword="null"/>。</summary>
    int? StatusCode { get; }
}
