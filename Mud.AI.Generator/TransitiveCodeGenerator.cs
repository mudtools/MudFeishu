using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Mud.AI;

/// <summary>
/// 代码生成器基类。
/// </summary>
public abstract class TransitiveCodeGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public abstract void Initialize(IncrementalGeneratorInitializationContext context);

    /// <summary>生成代码上标注的 <c>[CompilerGenerated]</c> 特性文本。</summary>
    protected const string CompilerGeneratedAttribute = GeneratedCodeConsts.CompilerGeneratedAttribute;

    /// <summary>生成代码上标注的 <c>[GeneratedCode]</c> 特性文本。</summary>
    protected static string GeneratedCodeAttribute => GeneratedCodeConsts.GeneratedCodeAttribute;


    /// <summary>
    /// 获取生成代码的默认引入的命名空间。
    /// </summary>
    /// <returns></returns>
    /// <remarks>
    /// NEW-GEN-13 修复：原默认列表仅含 4 个命名空间，不包含生成代码实际依赖的
    /// System.Net.Http、System.Threading、System.Text.Json、Mud.AI 等。
    /// 若子类未重写此方法且消费项目未配置 GlobalUsings.cs，生成代码可能因缺少 using 而编译失败。
    /// 修复后扩展为生成代码实际依赖的完整命名空间集合。
    /// </remarks>
    protected virtual Collection<string> GetFileUsingNameSpaces()
    {
        return
        [
            "System",
            "System.Collections.Generic",
            "System.ComponentModel.DataAnnotations",
            "System.Linq",
            "System.Linq.Expressions",
            "System.Net.Http",
            "System.Runtime.CompilerServices",
            "System.Text.Json",
            "System.Text.Json.Serialization",
            "System.Threading",
            "System.Threading.Tasks",
            "Microsoft.Extensions.Logging",
            "Mud.AI",
            "Mud.AI.Observability"
        ];
    }

    /// <summary>
    /// 生成通用的文件头部
    /// </summary>
    /// <param name="sb">代码构建器。</param>
    /// <param name="usingNamespaces">需要引入的命名空间。</param>
    /// <param name="emitNullableEnable">是否发射 #nullable enable（默认 true）。</param>
    public static void GenerateFileHeader(StringBuilder sb, IEnumerable<string> usingNamespaces, bool emitNullableEnable = true)
    {
        // [Phase4 修复 5.1] 公开 API 的参数守卫（CA1062）：本方法为库的公开契约入口，
        // 显式校验可把「调用方传 null」的 NRE 提前为参数异常（源生成器内 NRE 会被 csc 报为 AD0001）。
        if (sb == null)
            throw new ArgumentNullException(nameof(sb));
        if (usingNamespaces == null)
            throw new ArgumentNullException(nameof(usingNamespaces));

        // FIX-16: 固定换行符为 \n，避免 Windows(\r\n) 与 Linux(\n) 生成不同字节
        sb.Append("// <auto-generated/>\n");
        sb.Append("// 此代码由Mud源生成器自动生成，请勿手动修改\n");
        sb.Append('\n');
        if (emitNullableEnable)
            sb.Append("#nullable enable\n");

        foreach (var usingNamespace in usingNamespaces)
        {
            sb.Append($"using {usingNamespace};\n");
        }
    }

    /// <summary>
    /// 生成通用的文件头部（使用子类提供的命名空间）。
    /// </summary>
    /// <remarks>
    /// G9-07：<paramref name="emitNullableEnable"/> 由调用方显式传入（参数化），移除原实例可变属性
    /// <c>EmitNullableEnable</c>——增量生成器实例跨编译代复用，可变属性依赖「每次 ExecuteGenerator
    /// 先赋值后生成」的顺序纪律，属脆弱的隐式契约；实现类文件路径（ClassStructureGenerator）已是参数传递，
    /// 此处对齐为同一机制。
    /// </remarks>
    public void GenerateFileHeader(StringBuilder sb, bool emitNullableEnable)
    {
        GenerateFileHeader(sb, GetFileUsingNameSpaces(), emitNullableEnable);
    }


    /// <summary>
    /// 获取XML文档注释
    /// </summary>
    protected string GetXmlDocumentation(SyntaxNode syntaxNode)
    {
        if (syntaxNode == null)
            return string.Empty;

        var leadingTrivia = syntaxNode.GetLeadingTrivia();
        var xmlDocTrivia = leadingTrivia.FirstOrDefault(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia) ||
                                                             t.IsKind(SyntaxKind.MultiLineDocumentationCommentTrivia));

        if (xmlDocTrivia != default)
        {
            return xmlDocTrivia.ToFullString();
        }

        return string.Empty;
    }

    /// <summary>
    /// 报告生成错误的诊断信息（带精确位置）
    /// </summary>
    /// <param name="context">源码生成上下文</param>
    /// <param name="descriptor">诊断描述符</param>
    /// <param name="className">类名</param>
    /// <param name="exception">异常信息</param>
    /// <param name="location">错误位置</param>
    protected void ReportErrorDiagnostic(
        SourceProductionContext context,
        DiagnosticDescriptor descriptor,
        string className,
        Exception exception,
        Location location)
    {
        context.ReportDiagnostic(Diagnostic.Create(descriptor, location ?? Location.None, className, GeneratorDebugLogger.FormatExceptionMessage(exception)));
    }

    /// <summary>
    /// 生成代码语法验证的跳过开关（F-6）：环境变量 <c>MudHttpSkipGeneratedValidation=true|1</c> 时跳过。
    /// </summary>
    /// <remarks>
    /// 用环境变量而非 build_property 的原因：本验证方法标 <c>[Conditional("DEBUG")]</c>，
    /// Release 编译时调用点被整体剥离，MSBuild 编译期属性无消费点；而 DEBUG 下需要在
    /// 运行于编译器进程内的验证执行时机做运行时判定，环境变量是唯一稳定通道。
    /// 每次调用读取（而非静态缓存）以保持可测试性；读取开销远小于被跳过的 ParseText 全量解析。
    /// </remarks>
    internal static bool ShouldSkipGeneratedValidation()
    {
        var value = Environment.GetEnvironmentVariable("MudHttpSkipGeneratedValidation");
        return string.Equals(value, "true", StringComparison.OrdinalIgnoreCase)
            || string.Equals(value, "1", StringComparison.Ordinal);
    }

    /// <summary>
    /// 在 DEBUG 构建下验证生成代码的语法正确性（S1 优化建议）。
    /// 使用 <c>CSharpSyntaxTree.ParseText</c> 解析生成代码，发现语法错误时记录日志。
    /// Release 构建下此方法被 [Conditional("DEBUG")] 移除，零开销；
    /// DEBUG 下可经 <c>MudHttpSkipGeneratedValidation=true</c> 环境变量跳过（F-6）。
    /// </summary>
    [Conditional("DEBUG")]
    internal static void ValidateGeneratedCode(string hintName, string code)
    {
        if (ShouldSkipGeneratedValidation())
        {
            return;
        }

        try
        {
            var tree = CSharpSyntaxTree.ParseText(SourceText.From(code, Encoding.UTF8));
            foreach (var diag in tree.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error))
            {
                // [Phase4 修复 5.1] 显式 InvariantCulture（CA1305）：诊断文本仅用于日志，
                // 不应受当前区域设置影响（否则日志在不同机器上不可比）。
                GeneratorDebugLogger.Log($"生成代码语法错误 [{hintName}]: {diag.GetMessage(System.Globalization.CultureInfo.InvariantCulture)}");
            }
        }
        catch
        {
            // 验证失败不应阻断生成
        }
    }

    /// <summary>
    /// 添加生成源代码，并在 DEBUG 构建下验证语法正确性。
    /// </summary>
    internal static void AddSourceValidated(SourceProductionContext context, string hintName, string code)
    {
        ValidateGeneratedCode(hintName, code);
        context.AddSource(hintName, SourceText.From(code, Encoding.UTF8));
    }

}