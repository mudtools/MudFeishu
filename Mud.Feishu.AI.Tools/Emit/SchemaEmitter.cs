namespace Mud.Feishu.AI.Tools.Emit;

/// <summary>
/// Tier C 发射器：产出 <c>FeishuToolSchemas.g.cs</c>（Schema 常量 + 名字注册表）、
/// <c>FeishuToolNames.g.cs</c>（工具名契约表）、<c>FeishuToolContracts.g.cs</c>（类型化契约表）
/// 以及 golden 快照比对。
/// </summary>
/// <remarks>
/// <para>
/// <b>D2「单一真相源」落地</b>：工具名常量、只读/写类清单与 <c>IsWriteTool</c> 判定<b>不再手写</b>，
/// 全部从 <c>[FeishuTool]</c> 特性派生——原先"特性表 + 名字常量表 + 数组清单"三处平行手写，
/// 任何一处漏改都会静默漂移（名字常量编译期不报错，只在运行期表现为"白名单里的名字不存在"）。
/// </para>
/// <para>
/// <b>名字契约的所有者唯一</b>：工具名契约表只发射进 <c>Mud.Feishu.AI.FeishuTools</c> 程序集
/// （工具面的实现包）。其他引用本生成器的工程（AI 底座、测试工程）也可能声明
/// <c>[FeishuTool]</c> 样例接口，若一并发射会同名类型冲突（CS0433）。
/// </para>
/// </remarks>
internal static class SchemaEmitter
{
    /// <summary>工具名契约表所有者的程序集名。</summary>
    public const string ToolNamesOwnerAssembly = "Mud.Feishu.AI.FeishuTools";

    /// <summary>golden 快照文件名（由 csproj 以 <c>AdditionalFiles</c> 声明）。</summary>
    public const string GoldenFileName = "FeishuToolSchemas.golden.txt";

    /// <summary>
    /// 发射 Schema 常量与工具名契约表；返回 golden 漂移描述（<see langword="null"/> 表示一致）。
    /// </summary>
    /// <param name="context">源产出上下文。</param>
    /// <param name="models">Tier C 模型集合（已按工具名判重）。</param>
    /// <param name="assemblyName">当前编译的程序集名（决定是否发射名字契约表）。</param>
    /// <param name="goldenText">golden 快照内容（未声明 AdditionalFile 时为 <see langword="null"/>）。</param>
    /// <returns>golden 漂移描述（供 MUDFT014 上报）。</returns>
    public static string? Emit(
        SourceProductionContext context,
        ImmutableArray<ToolSchemaModel> models,
        string? assemblyName,
        string? goldenText)
    {
        if (models.IsEmpty)
        {
            return null;
        }

        var ordered = models
            .OrderBy(static m => m.Entry.ToolName, StringComparer.Ordinal)
            .ToArray();

        EmitSchemas(context, ordered);

        if (string.Equals(assemblyName, ToolNamesOwnerAssembly, StringComparison.Ordinal))
        {
            EmitToolNames(context, ordered);
            EmitContracts(context, ordered);
        }

        var golden = BuildGolden(ordered);
        if (goldenText is null)
        {
            return null;
        }

        return string.Equals(Normalize(goldenText), golden, StringComparison.Ordinal)
            ? null
            : DiffSummary(goldenText, golden);
    }

    /// <summary>构造 golden 快照文本（确定性：按工具名排序，一行一工具）。</summary>
    public static string BuildGolden(IReadOnlyList<ToolSchemaModel> ordered)
    {
        var sb = new StringBuilder();
        foreach (var model in ordered)
        {
            sb.Append(model.Entry.ToolName)
                .Append('\t')
                .Append(WriteSchema(model))
                .Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>渲染单个工具的描述符（唯一入口，保证常量与 golden 出自同一调用）。</summary>
    private static string WriteSchema(ToolSchemaModel model)
        => SchemaWriter.WriteToolSchema(model.Entry, model.Source);

    // ────────── FeishuToolSchemas.g.cs ──────────

    private static void EmitSchemas(SourceProductionContext context, ToolSchemaModel[] ordered)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated> 由 FeishuToolSchemaGenerator 编译期产出，禁止手工修改 </auto-generated>");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable CS1591 // 生成代码不逐一补 XML 注释");
        source.AppendLine("namespace Mud.Feishu.AI.Tools.Generated");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>[FeishuTool] 接口编译期产出的工具 Schema（AOT 安全：零运行时反射）。</summary>");
        source.AppendLine($"    {GeneratedCodeMarker.Attribute}");
        source.AppendLine("    public static partial class FeishuToolSchemas");
        source.AppendLine("    {");

        foreach (var model in ordered)
        {
            source.AppendLine($"        public const string {model.ConstName} = {JsonText.ToCSharpLiteral(WriteSchema(model))};");
            source.AppendLine();
        }

        source.AppendLine("        /// <summary>工具名 → Schema 的注册表快照（供白名单注册、授权审计与目录投影消费）。</summary>");
        source.AppendLine($"        {GeneratedCodeMarker.Attribute}");
        source.AppendLine("        public static System.Collections.Generic.IReadOnlyDictionary<string, string> SchemaByToolName { get; } =");
        source.AppendLine("            new System.Collections.Generic.Dictionary<string, string>(System.StringComparer.Ordinal)");
        source.AppendLine("            {");
        foreach (var model in ordered)
        {
            source.AppendLine($"                [{JsonText.ToCSharpLiteral(model.Entry.ToolName)}] = {model.ConstName},");
        }

        source.AppendLine("            };");
        source.AppendLine("    }");
        source.AppendLine("}");

        context.AddSource("FeishuToolSchemas.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    // ────────── FeishuToolNames.g.cs ──────────

    private static void EmitToolNames(SourceProductionContext context, ToolSchemaModel[] ordered)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated> 由 FeishuToolSchemaGenerator 编译期产出，禁止手工修改 </auto-generated>");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable CS1591 // 生成代码不逐一补 XML 注释");
        source.AppendLine("namespace Mud.Feishu.AI.FeishuTools");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>工具名契约表（编译期从 [FeishuTool] 特性派生）：模型可见契约的唯一真相源。</summary>");
        source.AppendLine($"    {GeneratedCodeMarker.Attribute}");
        source.AppendLine("    public static class FeishuToolNames");
        source.AppendLine("    {");

        foreach (var model in ordered)
        {
            var constant = BuildNameConstant(model.Entry.ToolName);
            source.AppendLine($"        public const string {constant} = {JsonText.ToCSharpLiteral(model.Entry.ToolName)};");
        }

        source.AppendLine();
        source.AppendLine("        /// <summary>只读工具契约名（全部 [FeishuTool(IsWrite=false)] 接口）。</summary>");
        source.AppendLine("        public static readonly string[] ReadonlyAll =");
        source.AppendLine("        [");
        foreach (var model in ordered.Where(static m => !m.IsWrite))
        {
            source.AppendLine($"            {BuildNameConstant(model.Entry.ToolName)},");
        }

        source.AppendLine("        ];");
        source.AppendLine();
        source.AppendLine("        /// <summary>写类工具契约名（全部 [FeishuTool(IsWrite=true)] 接口；白名单单独键控）。</summary>");
        source.AppendLine("        public static readonly string[] WriteAll =");
        source.AppendLine("        [");
        foreach (var model in ordered.Where(static m => m.IsWrite))
        {
            source.AppendLine($"            {BuildNameConstant(model.Entry.ToolName)},");
        }

        source.AppendLine("        ];");
        source.AppendLine();
        source.AppendLine("        /// <summary>全部契约名（只读 + 写）。</summary>");
        source.AppendLine("        public static readonly string[] All = [.. ReadonlyAll, .. WriteAll];");
        source.AppendLine();
        source.AppendLine("        /// <summary>判断工具名是否写类（读写白名单分离与授权门禁的事实来源）。</summary>");
        source.AppendLine($"        {GeneratedCodeMarker.Attribute}");
        source.AppendLine("        public static bool IsWriteTool(string name)");
        source.AppendLine("            => System.Linq.Enumerable.Contains(WriteAll, name, System.StringComparer.Ordinal);");
        source.AppendLine();
        source.AppendLine("        /// <summary>由工具名求契约常量名（诊断与守卫消费；不是契约本身）。</summary>");
        source.AppendLine($"        {GeneratedCodeMarker.Attribute}");
        source.AppendLine("        public static string? ToConstantName(string toolName) => toolName switch");
        source.AppendLine("        {");
        foreach (var model in ordered)
        {
            source.AppendLine($"            {JsonText.ToCSharpLiteral(model.Entry.ToolName)} => {BuildNameConstant(model.Entry.ToolName)},");
        }

        source.AppendLine("            _ => null,");
        source.AppendLine("        };");
        source.AppendLine("    }");
        source.AppendLine("}");

        context.AddSource("FeishuToolNames.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    // ────────── FeishuToolContracts.g.cs ──────────

    /// <summary>
    /// 发射类型化契约表（WP2 / R-B 根因）：契约事实（risk/identity/scopes/isWrite/http/route）的
    /// <b>类型化出口</b>——下游（注册器、目录、宿主策略默认值）直接消费编译期常量，
    /// 不再运行期解析 Schema JSON。
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>与 Schema 常量同一 pass</b>（零新增扫描）：字段取值与 <c>SchemaWriter.WriteExtension</c>
    /// 的 JSON 字面量逐一对齐（<c>IsWrite = Risk != Read</c> 是既有派生式，非声明标志），
    /// 保证"契约表 vs Schema JSON"不构成第二真相源。
    /// </para>
    /// <para>
    /// <b>类型可见性</b>：契约 record 的 <c>Risk</c> 直接使用 <c>Mud.Feishu.AI</c> 的
    /// <c>FeishuToolRisk</c> 枚举——契约源码被注入消费方（FeishuTools）程序集，而消费方引用
    /// AI 包，故枚举在其编译视角可见；生成器工程本身无需引用任何运行时包（包依赖图零变化）。
    /// 只发射进 <see cref="ToolNamesOwnerAssembly"/>（与 FeishuToolNames 同款门槛），
    /// 否则其他声明 <c>[FeishuTool]</c> 样例接口的工程会因找不到该枚举而 CS0246。
    /// </para>
    /// </remarks>
    private static void EmitContracts(SourceProductionContext context, ToolSchemaModel[] ordered)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated> 由 FeishuToolSchemaGenerator 编译期产出，禁止手工修改 </auto-generated>");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable CS1591 // 生成代码不逐一补 XML 注释");
        source.AppendLine("namespace Mud.Feishu.AI.Tools.Generated");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>工具契约（编译期常量视图，单一真相源 = [FeishuTool] 特性 + SDK 符号）。</summary>");
        source.AppendLine("    /// <remarks>与 FeishuToolSchemas 的 JSON 字面量出自同一 pass，仅形态不同（类型化 vs 字符串）。</remarks>");
        source.AppendLine("    public sealed record FeishuToolContract(");
        source.AppendLine("        string Name,");
        source.AppendLine("        string Description,");
        source.AppendLine("        Mud.Feishu.AI.Tools.FeishuToolRisk Risk,");
        source.AppendLine("        string Identity,");
        source.AppendLine("        bool IsWrite,");
        source.AppendLine("        string[] RequiredScopes,");
        source.AppendLine("        string SdkSource,");
        source.AppendLine("        string HttpMethod,");
        source.AppendLine("        string Route,");
        source.AppendLine("        string ParametersSchemaJson);");
        source.AppendLine();
        source.AppendLine("    /// <summary>工具契约表（按名索引；顺序与 golden 一致，保证确定性）。</summary>");
        source.AppendLine("    public static class FeishuToolContracts");
        source.AppendLine("    {");

        foreach (var model in ordered)
        {
            source.AppendLine($"        /// <summary>{model.Entry.ToolName} 的编译期契约。</summary>");
            source.AppendLine($"        public static FeishuToolContract {BuildNameConstant(model.Entry.ToolName)} {{ get; }} = new(");
            source.AppendLine($"            Name: {JsonText.ToCSharpLiteral(model.Entry.ToolName)},");
            source.AppendLine($"            Description: {JsonText.ToCSharpLiteral(model.Entry.DocSummary ?? string.Empty)},");
            source.AppendLine($"            Risk: {RiskLiteral(model.Entry.Risk)},");
            source.AppendLine($"            Identity: {JsonText.ToCSharpLiteral(model.Entry.Identity.ToString().ToLowerInvariant())},");
            source.AppendLine($"            IsWrite: {(model.Entry.Risk != ToolRisk.Read ? "true" : "false")},");
            source.AppendLine($"            RequiredScopes: {ScopeArrayLiteral(model.Entry.Scopes)},");
            source.AppendLine($"            SdkSource: {JsonText.ToCSharpLiteral(model.Source ?? string.Empty)},");
            source.AppendLine($"            HttpMethod: {JsonText.ToCSharpLiteral(model.Entry.HttpMethod ?? string.Empty)},");
            source.AppendLine($"            Route: {JsonText.ToCSharpLiteral(model.Entry.RouteTemplate ?? string.Empty)},");
            source.AppendLine($"            ParametersSchemaJson: {JsonText.ToCSharpLiteral(SchemaWriter.WriteInputSchema(model.Entry))});");
            source.AppendLine();
        }

        source.AppendLine("        /// <summary>工具名 → 契约的注册表快照（注册器/目录/守卫的唯一契约消费点）。</summary>");
        source.AppendLine("        public static System.Collections.Generic.IReadOnlyDictionary<string, FeishuToolContract> ByToolName { get; } =");
        source.AppendLine("            new System.Collections.Generic.Dictionary<string, FeishuToolContract>(System.StringComparer.Ordinal)");
        source.AppendLine("            {");
        foreach (var model in ordered)
        {
            source.AppendLine($"                [{JsonText.ToCSharpLiteral(model.Entry.ToolName)}] = {BuildNameConstant(model.Entry.ToolName)},");
        }

        source.AppendLine("            };");
        source.AppendLine();
        source.AppendLine("        /// <summary>全部契约名（与 FeishuToolNames.All 同源同序）。</summary>");
        source.AppendLine("        public static string[] AllNames { get; } =");
        source.AppendLine("        [");
        foreach (var model in ordered)
        {
            source.AppendLine($"            {JsonText.ToCSharpLiteral(model.Entry.ToolName)},");
        }

        source.AppendLine("        ];");
        source.AppendLine();
        source.AppendLine("        /// <summary>契约中实际出现的身份集合（宿主策略默认值/闭集校验的派生依据）。</summary>");
        source.AppendLine($"        public static string[] DistinctIdentities {{ get; }} = {StringArrayLiteral(DistinctIdentities(ordered))};");
        source.AppendLine();
        source.AppendLine("        /// <summary>契约中实际出现的 scope 全集（scope 权威清单校验用，去重后按序）。</summary>");
        source.AppendLine($"        public static string[] AllRequiredScopes {{ get; }} = {StringArrayLiteral(DistinctScopes(ordered))};");
        source.AppendLine("    }");
        source.AppendLine("}");

        context.AddSource("FeishuToolContracts.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    /// <summary>内部风险分级 → 消费方 <c>FeishuToolRisk</c> 枚举字面量（取值逐一对齐，见 FeishuToolRegistry 注释）。</summary>
    private static string RiskLiteral(ToolRisk risk) => risk switch
    {
        ToolRisk.Write => "Mud.Feishu.AI.Tools.FeishuToolRisk.Write",
        ToolRisk.HighRiskWrite => "Mud.Feishu.AI.Tools.FeishuToolRisk.HighRiskWrite",
        _ => "Mud.Feishu.AI.Tools.FeishuToolRisk.Read",
    };

    /// <summary>scope 数组字面量（空集为 <c>System.Array.Empty&lt;string&gt;()</c>，避免 <c>new[] { }</c> 非法）。</summary>
    private static string ScopeArrayLiteral(IReadOnlyList<string> scopes)
        => scopes.Count == 0
            ? "System.Array.Empty<string>()"
            : "new[] { " + string.Join(", ", scopes.Select(static s => JsonText.ToCSharpLiteral(s))) + " }";

    /// <summary>字符串数组字面量。</summary>
    private static string StringArrayLiteral(IReadOnlyList<string> values)
        => "[" + string.Join(", ", values.Select(static v => JsonText.ToCSharpLiteral(v))) + "]";

    /// <summary>契约中实际出现的身份集合（去重、按序）。</summary>
    private static List<string> DistinctIdentities(ToolSchemaModel[] ordered)
        => ordered
            .Select(static m => m.Entry.Identity.ToString().ToLowerInvariant())
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static v => v, StringComparer.Ordinal)
            .ToList();

    /// <summary>契约中实际出现的 scope 全集（去重、按序）。</summary>
    private static List<string> DistinctScopes(ToolSchemaModel[] ordered)
        => ordered
            .SelectMany(static m => m.Entry.Scopes)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static v => v, StringComparer.Ordinal)
            .ToList();

    /// <summary>工具名 → PascalCase 常量名（<c>bitable.list_tables</c> → <c>BitableListTables</c>）。</summary>
    public static string BuildNameConstant(string toolName)
    {
        var sb = new StringBuilder(toolName.Length);
        var upperNext = true;
        foreach (var ch in toolName)
        {
            if (ch is '.' or '_' or '-')
            {
                upperNext = true;
                continue;
            }

            sb.Append(upperNext ? char.ToUpperInvariant(ch) : ch);
            upperNext = false;
        }

        if (sb.Length == 0)
        {
            return "Unknown";
        }

        if (!char.IsLetter(sb[0]))
        {
            sb.Insert(0, 'T');
        }

        return sb.ToString();
    }

    // ────────── golden 比对 ──────────

    private static string Normalize(string text)
    {
        var normalized = text.Replace("\r\n", "\n").Replace('\r', '\n');
        return normalized.EndsWith("\n", StringComparison.Ordinal) ? normalized : normalized + "\n";
    }

    private static string DiffSummary(string goldenText, string actual)
    {
        var expected = Normalize(goldenText).Split('\n');
        var actualLines = actual.Split('\n');

        var expectedNames = Names(expected);
        var actualNames = Names(actualLines);

        var added = actualNames.Except(expectedNames, StringComparer.Ordinal).ToArray();
        var removed = expectedNames.Except(actualNames, StringComparer.Ordinal).ToArray();

        if (added.Length > 0 || removed.Length > 0)
        {
            var parts = new List<string>();
            if (added.Length > 0)
            {
                parts.Add($"新增 [{string.Join(", ", added)}]");
            }

            if (removed.Length > 0)
            {
                parts.Add($"消失 [{string.Join(", ", removed)}]");
            }

            return string.Join("；", parts);
        }

        var changed = actualNames
            .Where(name => !string.Equals(Lookup(expected, name), Lookup(actualLines, name), StringComparison.Ordinal))
            .ToArray();

        return changed.Length > 0
            ? $"描述符变更 [{string.Join(", ", changed)}]"
            : "格式差异（工具集与描述符内容一致）";
    }

    private static string[] Names(string[] lines)
        => lines
            .Where(static l => l.Length > 0)
            .Select(static l => l.Substring(0, l.IndexOf('\t') < 0 ? l.Length : l.IndexOf('\t')))
            .ToArray();

    private static string? Lookup(string[] lines, string name)
        => lines.FirstOrDefault(l => l.StartsWith(name + "\t", StringComparison.Ordinal));
}
