namespace Mud.Feishu.AI.Agents;

/// <summary>
/// 飞书域 guidance 资产的预算常量（<b>产品语义</b>，故留在飞书侧；装配机制在
/// <see cref="Mud.AI.Agent.Guidance.GuidanceComposer"/>）。
/// </summary>
/// <remarks>
/// <para>
/// <b>为什么预算不在中立包（H2 中立化决策）</b>：下文全部数值都来自<b>飞书域资产</b>的实测长度与
/// 余量策略（每一轮都是"内容加长 → 先复算总量 → 再抬常量"），属于产品语义。
/// 把它搬进中立装配器＝把某个产品的预算焊进包族底层，与「共享结构、不共享语义」冲突。
/// 故装配器只接收 <c>maxGuidanceLength</c> 参数，本类型是飞书侧的唯一取值来源。
/// </para>
/// <para>
/// <b>为什么是常量而非配置键</b>（对齐 R4.1/R-4 与 R5 治理：每个公开配置属性都必须有真实消费点
/// 与守卫登记；当前没有第二个取值需求）。超限按<b>整域丢弃</b>，失败方式为静默
/// （仅装配结果上的 <c>Truncated</c>/<c>OmittedDomains</c> 可查）。
/// </para>
/// <para>
/// <b>额度只计域 guidance 本体</b>（含块间分隔符），不含宿主 <c>Instructions</c>——
/// 宿主指令长度不该决定域资产是否被注入（P1-6）。
/// </para>
/// <para>
/// <b>R5 / B-12（2048 → 8192）</b>：原值 2048 是按"中文 UTF-8 3 字节/字符"估算的
/// （把 6,578 <b>字节</b>当成 ≈2,030 <b>字符</b>）。实测 14 个域合计<b>≈ 3,624 字符</b>
/// + 13 个分隔符 ≈ <b>3,650 字符</b>，<b>超原预算 78%</b>。而超限策略是"整域丢弃"，
/// 且遍历顺序由调用方给出（原为域名字母序）⇒ 溢出时<b>第 7 个域起共 8 个域
/// （feishu/im/task/mail/wiki/search/knowledge/sheets）的 guidance 从未进入过 prompt</b>。
/// 8192 &gt; 3,650 ⇒ 全域零丢弃，同时为 F-9 的结构化改造（每域 ≤ 2 KB）留出余量。
/// </para>
/// <para>
/// <b>R6 / S1（8192 → 16384）</b>：R6 把每个 L1 域资产从「前置链 + 避坑 + 示例」三节扩为
/// <b>五节</b>（新增「路由优先级」与「安全规则」），16 个域的域资产从 ≈3,650 涨到
/// <b>实测 12,836 字符</b>（域均值 ≈800 字符，单域上限 2048 未变）。若维持 8192，
/// 尾部域会被**静默整域丢弃**——即"深化了内容却一域都进不了 prompt"，这正是 R5/B-12
/// 已修过的失败形态，不能重犯。16384 对 12,836 留 ≈27% 余量（每域 ≈800 字符 ⇒ 约 4 个新域）。
/// </para>
/// <para>
/// <b>R7 / A4~A6（16384 → 24576）</b>：R7 新增三个域（Board / Attendance / Spark）的 L1 资产共
/// <b>4,629 字符</b>（三域分别 1,286 / 1,576 / 1,767），20 个域实测 <b>20,079 字符</b>——
/// 维持 16384 会让尾部域（按启用工具数降序）被整域丢弃。24576 对 20,079 留 ≈22% 余量。
/// </para>
/// <para>
/// <b>F-1（补域，24576 → 32768）</b>：F-1 新增两域（<c>mdm</c> ≈1,579 + <c>security</c> ≈1,901 字符，
/// 实测 23 个 L1 资产合计 <b>≈25,209 字符</b>，含块间分隔符）——维持 24576 会让尾部域被<b>整域丢弃</b>。
/// 32768 对 25,209 留 ≈30% 余量（≈4 个新域，与 R7 的"留出 4 个域"口径一致）。
/// </para>
/// <para>
/// 守卫：<c>GuidanceAssetContractGuards</c> 的"全域拼装零丢弃"用例锁死该不变量——
/// 未来再加长 md 会立刻报红，迫使本常量与内容长度同批评审。
/// </para>
/// </remarks>
public static class FeishuGuidanceBudget
{
    /// <summary>域 guidance 总长硬上限（字符数；超限按域顺序整域丢弃）。</summary>
    public const int MaxGuidanceLength = 32768;
}
