namespace Mud.Feishu.Webhook.Configuration;

/// <summary>
/// 应用专属拦截器与全局拦截器的组合策略（R3-P2-3）。
/// </summary>
/// <remarks>
/// <para>
/// <b>背景</b>：旧行为等价于 <see cref="AppOnly"/>——只要某应用注册了专属拦截器，
/// 全局拦截器就<b>被完全丢弃</b>。而拦截器通常是安全/审计类横切组件（签名复核、审计留痕、
/// 敏感事件告警），被静默丢弃意味着多应用部署下"配了全局审计却只对部分应用生效"，
/// 且没有任何告警。
/// </para>
/// <para>
/// 该策略与 <see cref="NonceFailureMode"/> / <see cref="InterceptionAckMode"/> 同形：
/// 宿主级策略用<b>配置</b>表达，不新增接口、不破坏既有实现。
/// </para>
/// </remarks>
public enum InterceptorFallbackMode
{
    /// <summary>
    /// 合并执行：**全局拦截器在前**，应用专属拦截器在后（默认）。
    /// </summary>
    /// <remarks>
    /// 全局先行是更安全的选择：安全/审计类横切应能先于应用逻辑决定是否放行。
    /// 任一拦截器返回 <c>false</c> 即中断后续（含应用专属拦截器）。
    /// </remarks>
    Merge = 0,

    /// <summary>
    /// 合并执行：应用专属拦截器在前，全局拦截器在后。
    /// </summary>
    /// <remarks>适用于"应用侧先做白名单/租户过滤，通过后再走全局审计"的场景。</remarks>
    AppThenGlobal = 1,

    /// <summary>
    /// 仅执行应用专属拦截器（<b>旧行为</b>，全局拦截器被丢弃）。
    /// </summary>
    /// <remarks>
    /// 仅为兼容旧语义保留。选用时若存在全局拦截器，启动期会输出一次 Warning
    /// 列出被屏蔽的全局拦截器类型。
    /// </remarks>
    AppOnly = 2
}
