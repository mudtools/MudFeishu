using Xunit;

// ============================================================================================
// 本测试程序集**禁用测试类并行**——不要移除本行，除非同时解决了下方记录的两个正交缺陷面。
//
// 背景：本程序集存在多处「进程级静态状态」，其中最具代表性的是
// Mud.Feishu.Abstractions.Authentication.TokenStorePurgeGate（清库门）。xUnit 默认按
// **测试类**（collection）并行执行，于是不同类会并发读写同一份静态状态，导致随机失败——
// 实测曾出现 TokenStorePurgeGateTests.Gate_ShouldTrackLeasesPerAppKey 偶发红
// （全量门禁连跑 5 轮命中 1 次；单跑该类 6 轮全绿，是典型的跨类干扰指纹）。
//
// 为什么不用「把相关类圈进同一个 xUnit Collection」（仓库中 Metrics 系列就是这么做的，
// 见 Metrics/FeishuMetricsCollection.cs）？
//   因为门的**变更者集合是开放的、无法在编译期枚举**：
//   ① 直接调用者有 4 个测试类；
//   ② 间接来源是 FeishuAppManager 的凭据轮换热更新（FeishuAppManager.cs 的 Mark/Release），
//      即「只要某个用例改变了 AppId/AppSecret 并触发热更新」就会打门——
//      这个集合随新用例增长，用 Collection 手工标注必然漏，漏了就回到随机红。
//
//   另外还有一个 **Collection 也挡不住** 的面：清库是 `Task.Run` fire-and-forget 执行的，
//   其 `finally { Release(...) }` 会跨越测试边界落地，可能把下一个用例刚打上的门减掉。
//   该项已由 TokenStorePurgeGate 的「世代隔离（ResetForTest 递增 _epoch）」单独根治，
//   与本处的并行治理是两个正交面，缺一不可。
//   ⇒ 只做本地依据：不要因为加了本行就去动 _epoch 隔离，也不要因为有了 _epoch 就移除本行。
//
// 代价（已实测）：Mud.Feishu.Abstractions.Tests 共 ~764 个用例，并行时 test 段约 2s；
//   串行化为同一数量级（秒级），相对全仓门禁（8000+ 用例）可忽略。
//   用秒级开销换「消除一整类无法枚举的随机红」，取舍明确。
//
// 若将来确有需要恢复并行：请先把上述静态状态改为可注入实例（或推出异步查询 quiesce 能力），
// 再移除本行——顺序不可颠倒。
// ============================================================================================
[assembly: CollectionBehavior(DisableTestParallelization = true)]
